from pal import atari_rgb
from PIL import Image, ImageDraw
P = [atari_rgb(i) for i in range(256)]

def load(f):
    return bytearray(open(f, 'rb').read())

def put(d, x, y, c):                     # x en píxeles gordos (0-191)
    if 0 <= x < 192 and 0 <= y < 240:
        d[y * 384 + 2 * x] = c; d[y * 384 + 2 * x + 1] = c

def spr(d, x0, y0, art, cols, flipx=False):
    rows = art.strip('\n').split('\n')
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch in cols:
                put(d, x0 + ((len(r) - 1 - i) if flipx else i), y0 + j, cols[ch])

