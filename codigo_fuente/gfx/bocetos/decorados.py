def label(im, txt):
    dr = ImageDraw.Draw(im)
    dr.rectangle((0, 0, im.width, 18), fill=(0, 0, 0))
    dr.text((6, 3), txt, fill=(255, 220, 120))
    return im

def show(d):
    im = Image.new('RGB', (384, 240)); im.putdata([P[b] for b in d])
    return im.crop((32, 24, 352, 210)).resize((640, 372), Image.NEAREST)

F4 = '/tmp/v4/f00900.raw'; F5 = '/tmp/v5/f00900.raw'
paneles = []

# A: bosque lejano de empalados en la cordillera
d = load(F4)
for x in range(16, 180, 6):
    spr(d, x, 75 + ((x * 7) % 3), EMPL, {'#': 130})
